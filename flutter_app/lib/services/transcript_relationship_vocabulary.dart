/// Longest words first so compound roles keep their complete meaning.
String _wordsPattern(Iterable<String> vocabulary) {
  final words = vocabulary.toSet().toList()
    ..sort((a, b) => b.length.compareTo(a.length));
  return words
      .map((word) => word.split(' ').map(RegExp.escape).join(r'\s+'))
      .join('|');
}

